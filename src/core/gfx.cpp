void Framebuffer::fill_rect(int x, int y, int rw, int rh, uint16_t c) {
  const int x0 = x < 0 ? 0 : x;
  const int y0 = y < 0 ? 0 : y;
  const int x1 = x + rw > w ? w : x + rw;
  const int y1 = y + rh > h ? h : y + rh;
  for (int yy = y0; yy < y1; ++yy) {
    uint16_t* row = px + yy * w;
    for (int xx = x0; xx < x1; ++xx) row[xx] = c;
  }
}

int text_width(const char* s, int scale) {
  int n = 0;
  while (s[n]) ++n;
  return n == 0 ? 0 : (n * kAdvance - 1) * scale;
}

void draw_text(Framebuffer& fb, int x, int y, const char* s, uint16_t c, int scale) {
  for (; *s; ++s, x += kAdvance * scale) {
    const Glyph& g = find_glyph(*s);
    for (int row = 0; row < kGlyphH; ++row)
      for (int col = 0; col < kGlyphW; ++col)
        if (g.rows[row] & (1 << (kGlyphW - 1 - col)))
          fb.fill_rect(x + col * scale, y + row * scale, scale, scale, c);
  }
}

void draw_text_centered(Framebuffer& fb, int cx, int y, const char* s, uint16_t c, int scale) {
  draw_text(fb, cx - text_width(s, scale) / 2, y, s, c, scale);
}

