constexpr int kGlyphW = 5;
constexpr int kGlyphH = 7;
constexpr int kAdvance = kGlyphW + 1;

constexpr uint8_t bits(const char* s) {
  uint8_t v = 0;
  for (int i = 0; i < kGlyphW; ++i) v = static_cast<uint8_t>((v << 1) | (s[i] == '#' ? 1 : 0));
  return v;
}

