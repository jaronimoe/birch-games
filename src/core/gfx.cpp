const Glyph& find_glyph(char ch) {
  if (ch >= 'a' && ch <= 'z') ch = static_cast<char>(ch - 'a' + 'A');
  for (const Glyph& g : kGlyphs)
    if (g.ch == ch) return g;
  for (const Glyph& g : kGlyphs)
    if (g.ch == '?') return g;
  return kGlyphs[0];
}

